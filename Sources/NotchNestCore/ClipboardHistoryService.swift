import AppKit
import CoreImage
import Foundation
import Observation

@MainActor
@Observable
public final class ClipboardHistoryService {
    public private(set) var entries: [ClipboardEntry] = []
    public private(set) var isMonitoring = false

    private let persistence: PersistenceStore
    private var pollTimer: Timer?
    private var lastObservedChangeCount: Int
    private let maxUnpinnedEntries: Int
    private let maxStoredCharacters = 4_000

    private nonisolated static let sensitivePasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.1password.browser-support",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type"
    ]

    private nonisolated static let sensitiveBundlePrefixes: [String] = [
        "com.1password.",
        "com.agilebits.onepassword",
        "com.bitwarden.",
        "com.lastpass.",
        "com.dashlane.",
        "org.keepassx.",
        "org.keepassxc.",
        "com.apple.keychainaccess",
        "com.apple.passwords"
    ]

    public init(persistence: PersistenceStore, maxUnpinnedEntries: Int = 20) {
        self.persistence = persistence
        self.maxUnpinnedEntries = max(1, maxUnpinnedEntries)
        self.lastObservedChangeCount = NSPasteboard.general.changeCount
        self.entries = Self.normalizedOrder(
            persistence.loadClipboardHistory(),
            maxUnpinnedEntries: self.maxUnpinnedEntries
        )
    }

    public func startMonitoring() {
        stopMonitoring()
        lastObservedChangeCount = NSPasteboard.general.changeCount
        isMonitoring = true
        let timer = Timer(timeInterval: 1.0, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.pollPasteboardIfChanged()
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        pollTimer = timer
    }

    public func stopMonitoring() {
        pollTimer?.invalidate()
        pollTimer = nil
        isMonitoring = false
    }

    public func pollPasteboardIfChanged() {
        let pasteboard = NSPasteboard.general
        let currentCount = pasteboard.changeCount
        guard currentCount != lastObservedChangeCount else { return }
        lastObservedChangeCount = currentCount

        let frontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard !Self.isSensitivePasteboard(
            types: pasteboard.types ?? [],
            frontmostBundleID: frontmostBundleID
        ) else {
            return
        }

        if let text = pasteboard.string(forType: .string) {
            recordText(text)
        }
    }

    public func recordText(_ rawText: String, now: Date = Date()) {
        let trimmed = rawText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        let bounded = String(trimmed.prefix(maxStoredCharacters))

        if let existingIndex = entries.firstIndex(where: { $0.text == bounded }) {
            var updated = entries.remove(at: existingIndex)
            updated.addedAt = now
            entries.insert(updated, at: 0)
        } else {
            let entry = ClipboardEntry(text: bounded, addedAt: now)
            entries.insert(entry, at: 0)
        }

        entries = Self.normalizedOrder(entries, maxUnpinnedEntries: maxUnpinnedEntries)
        persistence.saveClipboardHistory(entries)
    }

    public func copyToPasteboard(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        lastObservedChangeCount = pasteboard.changeCount
    }

    public func togglePin(_ entryID: UUID) {
        guard let idx = entries.firstIndex(where: { $0.id == entryID }) else { return }
        entries[idx].isPinned.toggle()
        entries = Self.normalizedOrder(entries, maxUnpinnedEntries: maxUnpinnedEntries)
        persistence.saveClipboardHistory(entries)
    }

    public func remove(_ entryID: UUID) {
        entries.removeAll { $0.id == entryID }
        persistence.saveClipboardHistory(entries)
    }

    public func clearUnpinned() {
        entries.removeAll { !$0.isPinned }
        persistence.saveClipboardHistory(entries)
    }

    public nonisolated static func isSensitivePasteboard(
        types: [NSPasteboard.PasteboardType],
        frontmostBundleID: String?
    ) -> Bool {
        if let bundle = frontmostBundleID?.lowercased(),
           sensitiveBundlePrefixes.contains(where: { bundle.hasPrefix($0) }) {
            return true
        }
        for type in types {
            let raw = type.rawValue
            if sensitivePasteboardTypes.contains(raw) {
                return true
            }
            let lower = raw.lowercased()
            if lower.contains("concealed") || lower.contains("transientpasteboard") {
                return true
            }
        }
        return false
    }

    public nonisolated static func qrCodeImage(for text: String, size: CGFloat = 180) -> NSImage? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty,
              let data = trimmed.data(using: .utf8),
              let filter = CIFilter(name: "CIQRCodeGenerator") else {
            return nil
        }
        filter.setValue(data, forKey: "inputMessage")
        filter.setValue("M", forKey: "inputCorrectionLevel")

        guard let outputImage = filter.outputImage else { return nil }
        let extent = outputImage.extent.integral
        guard extent.width > 0, extent.height > 0 else { return nil }

        let targetPx = max(64, size * 2)
        let scale = max(1, floor(min(targetPx / extent.width, targetPx / extent.height)))
        let scaledImage = outputImage
            .samplingNearest()
            .transformed(by: CGAffineTransform(scaleX: scale, y: scale))

        let context = CIContext()
        guard let cgImage = context.createCGImage(scaledImage, from: scaledImage.extent) else {
            return nil
        }
        return NSImage(cgImage: cgImage, size: NSSize(width: size, height: size))
    }

    private static func normalizedOrder(_ rawEntries: [ClipboardEntry], maxUnpinnedEntries: Int) -> [ClipboardEntry] {
        let pinned = rawEntries
            .filter(\.isPinned)
            .sorted { $0.addedAt > $1.addedAt }
        let unpinned = rawEntries
            .filter { !$0.isPinned }
            .sorted { $0.addedAt > $1.addedAt }
            .prefix(maxUnpinnedEntries)
        return pinned + unpinned
    }
}
